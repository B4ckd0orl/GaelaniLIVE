WORD_RE = {en: re.compile(r"\b" + re.escape(en) + r"\b") for en, _ in WORDS}


def translate_text_chunk(t, words_map):
    """Translate whole words inside a text chunk (never inside identifiers)."""
    for en, es in words_map:
        t = WORD_RE[en].sub(es, t)
    return t


def apply_file(path):
    s = open(path, encoding="utf-8").read()
    n_phrase = 0
    for en, es in sorted(PHRASES, key=lambda p: -len(p[0])):
        c = s.count(en)
        if c:
            s = s.replace(en, es)
            n_phrase += c

    # text nodes: >...letters...<  (skip anything that looks like JS/CSS code)
    def repl_node(m):
        inner = m.group(1)
        if not re.search(r"[A-Za-z]", inner):
            return m.group(0)
        if len(inner) > 400:
            return m.group(0)
        if re.search(r"[;{}=`$]|=>|&&|\|\||\bvar\b|\bfunction\b|\breturn\b|\bnew\b", inner):
            return m.group(0)  # code-ish chunk between > and <, leave it alone
        return ">" + translate_text_chunk(inner, WORDS) + "<"
    s, n_nodes = re.subn(r">([^<>]+)<", repl_node, s)

    # attributes that hold human text (title, aria-label, placeholder, alt)
    def repl_attr(m):
        name, val = m.group(1), m.group(2)
        if not re.search(r"[A-Za-z]", val):
            return m.group(0)
        return f"{name}=\"{translate_text_chunk(val, WORDS)}\""
    s, n_attrs = re.subn(r"\b(title|aria-label|placeholder|alt)=\"([^\"]*)\"", repl_attr, s)

    open(path, "w", encoding="utf-8", newline="\n").write(s)
    return n_phrase + n_nodes


if __name__ == "__main__":
    for fn in ("gaelanilive_page.html", "gaelanilive_remote.html"):
        p = os.path.join(SRC, fn)
        n = apply_file(p)
        print(f"{fn}: {n} replacements applied")
